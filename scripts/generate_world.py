#!/usr/bin/env python3
"""Generate the Gazebo world SDF + landing-tag model from simulation/configs/world_ps05.yaml.

Usage: scripts/generate_world.py [--spec simulation/configs/world_ps05.yaml]
Outputs:
  simulation/worlds/<name>.sdf
  simulation/models/ps05_landing_tag/{model.config,model.sdf,materials/textures/tag36h11_<id>.png}
"""
import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]


def material(rgb, emissive=0.0):
    r, g, b = rgb
    return (f'<material><ambient>{r} {g} {b} 1</ambient><diffuse>{r} {g} {b} 1</diffuse>'
            f'<specular>0.1 0.1 0.1 1</specular><emissive>{r*emissive} {g*emissive} {b*emissive} 1</emissive></material>')


def geometry(o):
    t = o['type']
    if t == 'box':
        sx, sy, sz = o['size']
        return f'<box><size>{sx} {sy} {sz}</size></box>'
    if t == 'cylinder':
        return f"<cylinder><radius>{o['radius']}</radius><length>{o['length']}</length></cylinder>"
    if t == 'sphere':
        return f"<sphere><radius>{o['radius']}</radius></sphere>"
    raise ValueError(f'unknown obstacle type {t}')


def obstacle_model(o, static=True):
    x, y, z = o['pos']
    g = geometry(o)
    return f"""
    <model name="{o['name']}">
      <static>{'true' if static else 'false'}</static>
      <pose>{x} {y} {z} 0 0 0</pose>
      <link name="link">
        <gravity>false</gravity>
        <collision name="collision"><geometry>{g}</geometry></collision>
        <visual name="visual"><geometry>{g}</geometry>{material(o['color'])}</visual>
      </link>
    </model>"""


def tag_model(spec, models_dir: Path):
    import cv2  # noqa: F401  (container has OpenCV)
    sys.path.insert(0, str(ROOT / 'ros2_ws/src/landing_detector'))
    from landing_detector.marker import make_tag_image
    pad = spec['landing_pad']
    tag_id = int(pad['tag_id'])
    border_frac = (pad['tag_plate'] - pad['tag_size']) / 2.0 / pad['tag_size']
    img = make_tag_image('DICT_APRILTAG_36h11', tag_id, 800, border_frac)
    d = models_dir / 'ps05_landing_tag'
    (d / 'materials/textures').mkdir(parents=True, exist_ok=True)
    tex = f'tag36h11_{tag_id}.png'
    cv2.imwrite(str(d / 'materials/textures' / tex), img)
    (d / 'model.config').write_text(f"""<?xml version="1.0"?>
<model><name>ps05_landing_tag</name><version>1.0</version><sdf version="1.9">model.sdf</sdf>
<description>AprilTag 36h11 id {tag_id}, {pad['tag_size']} m tag on a {pad['tag_plate']} m white plate</description></model>
""")
    s = pad['tag_plate']
    (d / 'model.sdf').write_text(f"""<?xml version="1.0"?>
<sdf version="1.9">
  <model name="ps05_landing_tag">
    <static>true</static>
    <link name="link">
      <visual name="tag">
        <geometry><plane><normal>0 0 1</normal><size>{s} {s}</size></plane></geometry>
        <material>
          <ambient>1 1 1 1</ambient><diffuse>1 1 1 1</diffuse><specular>0 0 0 1</specular>
          <pbr><metal><albedo_map>materials/textures/{tex}</albedo_map><metalness>0</metalness><roughness>1</roughness></metal></pbr>
        </material>
      </visual>
    </link>
  </model>
</sdf>
""")


def world_sdf(spec):
    pad = spec['landing_pad']
    px, py = pad['center']
    sx, sy = pad['size']
    h = pad['height']
    models = ''.join(obstacle_model(o) for o in spec['obstacles'])
    models += ''.join(obstacle_model(o, static=True) for o in spec.get('dynamic', []))
    st = spec['tracking_station']
    return f"""<?xml version="1.0" ?>
<!-- GENERATED by scripts/generate_world.py from simulation/configs/world_ps05.yaml. Do not edit by hand. -->
<sdf version="1.9">
  <world name="{spec['name']}">
    <physics type="ode">
      <max_step_size>0.004</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>250</real_time_update_rate>
    </physics>
    <gravity>0 0 -9.8</gravity>
    <magnetic_field>6e-06 2.3e-05 -4.2e-05</magnetic_field>
    <atmosphere type="adiabatic"/>
    <plugin filename="gz-sim-physics-system" name="gz::sim::systems::Physics"/>
    <plugin filename="gz-sim-user-commands-system" name="gz::sim::systems::UserCommands"/>
    <plugin filename="gz-sim-scene-broadcaster-system" name="gz::sim::systems::SceneBroadcaster"/>
    <plugin filename="gz-sim-contact-system" name="gz::sim::systems::Contact"/>
    <plugin filename="gz-sim-imu-system" name="gz::sim::systems::Imu"/>
    <plugin filename="gz-sim-air-pressure-system" name="gz::sim::systems::AirPressure"/>
    <plugin filename="gz-sim-air-speed-system" name="gz::sim::systems::AirSpeed"/>
    <plugin filename="gz-sim-magnetometer-system" name="gz::sim::systems::Magnetometer"/>
    <plugin filename="gz-sim-sensors-system" name="gz::sim::systems::Sensors">
      <render_engine>ogre2</render_engine>
    </plugin>
    <scene>
      <grid>false</grid>
      <ambient>0.6 0.6 0.6 1</ambient>
      <background>0.70 0.80 0.95 1</background>
      <shadows>false</shadows>
    </scene>
    <spherical_coordinates>
      <surface_model>EARTH_WGS84</surface_model>
      <world_frame_orientation>ENU</world_frame_orientation>
      <latitude_deg>20.2961</latitude_deg>
      <longitude_deg>85.8245</longitude_deg>
      <elevation>30</elevation>
    </spherical_coordinates>
    <light type="directional" name="sun">
      <cast_shadows>false</cast_shadows>
      <pose>25 25 40 0 0 0</pose>
      <diffuse>0.9 0.9 0.9 1</diffuse>
      <specular>0.2 0.2 0.2 1</specular>
      <direction>-0.4 0.3 -0.9</direction>
    </light>
    <model name="ground_plane">
      <static>true</static>
      <link name="link">
        <collision name="collision"><geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry></collision>
        <visual name="visual"><geometry><plane><normal>0 0 1</normal><size>200 200</size></plane></geometry>
          {material([0.45, 0.52, 0.40])}</visual>
      </link>
    </model>
    <model name="arena_markings">
      <static>true</static>
      <link name="link">
        <visual name="arena"><pose>25 25 0.005 0 0 0</pose><geometry><plane><normal>0 0 1</normal><size>50 50</size></plane></geometry>
          {material([0.52, 0.56, 0.48])}</visual>
        <visual name="start_pad"><pose>{spec['start'][0]} {spec['start'][1]} 0.01 0 0 0</pose><geometry><box><size>2 2 0.02</size></box></geometry>
          {material([0.95, 0.95, 0.20])}</visual>
      </link>
    </model>
    <model name="landing_pad">
      <static>true</static>
      <pose>{px} {py} {h / 2} 0 0 0</pose>
      <link name="link">
        <collision name="collision"><geometry><box><size>{sx} {sy} {h}</size></box></geometry></collision>
        <visual name="visual"><geometry><box><size>{sx} {sy} {h}</size></box></geometry>{material([0.25, 0.25, 0.28])}</visual>
      </link>
    </model>
    <include>
      <uri>model://ps05_landing_tag</uri>
      <name>landing_tag</name>
      <pose>{px} {py} {h + 0.002} 0 0 0</pose>
    </include>
    <model name="tracking_station">
      <static>true</static>
      <pose>{st[0]} {st[1]} {st[2] / 2} 0 0 0</pose>
      <link name="link">
        <visual name="mast"><geometry><cylinder><radius>0.08</radius><length>{st[2]}</length></cylinder></geometry>{material([0.9, 0.9, 0.9])}</visual>
        <visual name="head"><pose>0 0 {st[2] / 2} 0 0 0</pose><geometry><sphere><radius>0.25</radius></sphere></geometry>{material([0.1, 0.8, 0.9], 0.3)}</visual>
      </link>
    </model>{models}
  </world>
</sdf>
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--spec', default=str(ROOT / 'simulation/configs/world_ps05.yaml'))
    ap.add_argument('--no-tag', action='store_true', help='skip tag texture generation (no OpenCV)')
    a = ap.parse_args()
    spec = yaml.safe_load(open(a.spec))
    out = ROOT / 'simulation/worlds' / f"{spec['name']}.sdf"
    out.write_text(world_sdf(spec))
    print(f'wrote {out}')
    if not a.no_tag:
        tag_model(spec, ROOT / 'simulation/models')
        print('wrote simulation/models/ps05_landing_tag')


if __name__ == '__main__':
    main()
